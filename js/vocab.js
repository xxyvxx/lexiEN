  normalize(word) {
    return String(word || "")
      .trim()
      .toLowerCase()
      .replace(/[’‘]/g, "'");
  },

  lookup(raw) {
    const key = this.normalize(raw);
    if (!key) return null;
    if (this.map[key]) return { en: key, ru: this.map[key] };

    const tryKey = (k) => (this.map[k] ? { en: k, ru: this.map[k] } : null);

    // -ies → y
    if (key.endsWith("ies")) {
      const hit = tryKey(`${key.slice(0, -3)}y`);
      if (hit) return hit;
    }
    // -ing
    if (key.endsWith("ing") && key.length > 5) {
      const base = key.slice(0, -3);
      let hit = tryKey(base) || tryKey(`${base}e`);
      if (hit) return hit;
      if (base.length > 2 && base[base.length - 1] === base[base.length - 2]) {
        hit = tryKey(base.slice(0, -1));
        if (hit) return hit;
      }
    }
    // -ed
    if (key.endsWith("ied")) {
      const hit = tryKey(`${key.slice(0, -3)}y`);
      if (hit) return hit;
    }
    if (key.endsWith("ed") && key.length > 4) {
      const hit = tryKey(key.slice(0, -2)) || tryKey(key.slice(0, -1)) || tryKey(`${key.slice(0, -2)}e`);
      if (hit) return hit;
    }
    // -es / -s
    if (key.endsWith("es") && key.length > 3) {
      const hit = tryKey(key.slice(0, -2)) || tryKey(key.slice(0, -1));
      if (hit) return hit;
    }
    if (key.endsWith("s") && key.length > 2) {
      const hit = tryKey(key.slice(0, -1));
      if (hit) return hit;
    }
    return null;
  },
